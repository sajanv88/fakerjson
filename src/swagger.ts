import type { INestApplication } from '@nestjs/common';
import { DocumentBuilder, type OpenAPIObject, SwaggerModule } from '@nestjs/swagger';
import type { AppConfig } from './config/app-config.js';
import { RESOURCE_GROUPS } from './data/resource.types.js';
import { APP_VERSION } from './version.js';
import { RESOURCES } from './resources/index.js';
import { tagOf } from './resources/resource-controller.factory.js';

const DESCRIPTION = `
Free fake REST API for prototypes, demos, tests and tutorials. A friendlier
[JSONPlaceholder](https://jsonplaceholder.typicode.com/), with realistic data generated by
[Faker](https://fakerjs.dev/).

### Highlights
- **Stable data.** Every row is generated from a seed, so \`GET /v1/users/7\` returns the same user
  every time, on every server. Add \`?seed=<n>\` for a different, equally stable dataset.
- **Real relations.** \`posts.userId\` points at a real user. Nested routes (\`/v1/users/7/posts\`) and
  \`?expand=user\` embed related rows.
- **Lists that behave like production.** Pagination (\`page\`, \`limit\`) with \`meta\`, \`links\`,
  \`X-Total-Count\` and \`Link\` headers; filters (\`?status=published\`, \`?price_gte=10\`),
  search (\`?q=\`), sorting (\`?sort=-createdAt,title\`) and sparse fields (\`?fields=id,title\`).
- **Faked writes.** \`POST\`, \`PUT\`, \`PATCH\` and \`DELETE\` validate the body and answer like a real API
  (201 + \`Location\`, 200, 204, 404, 422), but nothing is stored.
- **Localised data.** \`?locale=de\`, \`fr\`, \`ja\`, … for names, addresses and text in other languages.
- **Test the unhappy path.** \`?delay=1500\` slows any response; \`/v1/status/{code}\` returns any status.
- **Standard errors.** Every error is an RFC 9457 \`application/problem+json\` document.
- **HTTP caching.** \`ETag\` / \`If-None-Match\` (304) and \`Cache-Control\` on every read.

### Rate limits
Per client IP. Every response carries \`X-RateLimit-Limit\`, \`X-RateLimit-Remaining\` and
\`X-RateLimit-Reset\` (plus \`-burst\` and \`-writes\` variants); a 429 carries \`Retry-After\`.
`;

const TAG_DESCRIPTIONS: Record<string, string> = {
  Meta: 'API index.',
  Utilities: 'Helpers for testing loading and error states.',
};

export function buildOpenApiDocument(app: INestApplication, config: AppConfig): OpenAPIObject {
  const builder = new DocumentBuilder()
    .setTitle('FakerJson')
    .setDescription(DESCRIPTION.trim())
    .setVersion(APP_VERSION)
    .setLicense('MIT', 'https://opensource.org/licenses/MIT');
  if (config.PUBLIC_BASE_URL) builder.addServer(config.PUBLIC_BASE_URL);

  builder.addTag('Meta', TAG_DESCRIPTIONS.Meta);
  builder.addTag('Utilities', TAG_DESCRIPTIONS.Utilities);
  for (const group of RESOURCE_GROUPS) {
    for (const def of RESOURCES.filter((d) => d.group === group)) {
      builder.addTag(tagOf(def), `${def.description} ${def.count} rows.`);
    }
  }

  const document = SwaggerModule.createDocument(app, builder.build(), { autoTagControllers: false });

  // Redoc / Scalar / Stoplight read x-tagGroups to show the families as sections.
  (document as OpenAPIObject & { 'x-tagGroups': unknown })['x-tagGroups'] = [
    { name: 'Meta', tags: ['Meta', 'Utilities'] },
    ...RESOURCE_GROUPS.map((group) => ({
      name: group,
      tags: RESOURCES.filter((d) => d.group === group).map(tagOf),
    })).filter((g) => g.tags.length > 0),
  ];
  return document;
}

export function setupSwagger(app: INestApplication, config: AppConfig): void {
  if (!config.SWAGGER_ENABLED) return;
  let cached: OpenAPIObject | undefined;
  SwaggerModule.setup('docs', app, () => (cached ??= buildOpenApiDocument(app, config)), {
    jsonDocumentUrl: 'openapi.json',
    yamlDocumentUrl: 'openapi.yaml',
    customSiteTitle: 'FakerJson · Docs',
    swaggerOptions: {
      docExpansion: 'none',
      filter: true,
      displayRequestDuration: true,
      tryItOutEnabled: true,
      defaultModelsExpandDepth: 0,
      showExtensions: false,
    },
  });
}
